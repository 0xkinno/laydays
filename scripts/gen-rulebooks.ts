import { readFileSync, writeFileSync } from "node:fs";
const defs = readFileSync("data/rulebooks/laytime-definitions.md", "utf8");
const house = readFileSync("data/rulebooks/house-rules.v1.md", "utf8");
const demo = {
  sof: readFileSync("data/demo/sof.txt", "utf8"),
  cp: JSON.parse(readFileSync("data/demo/cp-clauses.json", "utf8")),
  calendar: JSON.parse(readFileSync("data/demo/port-calendar.json", "utf8")),
};
writeFileSync(
  "lib/serv/rulebooks.generated.ts",
  `// Generated by scripts/gen-rulebooks.ts from data/. Do not edit.\nexport const LAYTIME_DEFINITIONS = ${JSON.stringify(defs)};\nexport const HOUSE_RULES_V1 = ${JSON.stringify(house)};\nexport const DEMO = ${JSON.stringify(demo)} as const;\n`,
);
console.log("rulebooks generated");
